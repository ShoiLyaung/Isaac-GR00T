OLD_SCOPE = (
    "B1 original eager sampling; same pretraining-domain train/dev cohort, no final/reserve outputs"
)
FINAL_SCOPE = "B1 original eager sampling on the pre-frozen final16 cohort; reserve excluded; no checkpoint or episode selection from these outputs"
NATIVE_METRICS = ("flow_loss", "combined_mae_mixed_units", "arm_mae_rad", "hand_mae_u")


def read(path):
    import json

    return json.loads(Path(path).read_text())


def verify_final_contract(plan, cohort):
    final = plan["final"]
    if (
        final != cohort["final"]
        or len(final) != 16
        or len(set(final)) != 16
        or set(final) & set(cohort["reserve"])
    ):
        raise ValueError(
            "Exactly the pre-frozen final16 cohort is required; reserve is inaccessible"
        )
    if plan["noise_seeds"] != [42, 43, 44, 45]:
        raise ValueError("Frozen four nominal final sampling seeds required")
    for ep in final:
        anchors = plan["eval_anchors"][str(ep)]
        length = plan["lengths"][str(ep)]
        if (
            len(anchors) != 32
            or anchors != sorted(set(anchors))
            or any(type(a) is not int or a < 0 or a % 4 or a > length - 16 for a in anchors)
        ):
            raise ValueError("Each final episode requires32 fixed unique legal stride4 anchors")
    bootstrap = plan["paired_bootstrap"]
    if (bootstrap["resamples"], bootstrap["seed"], bootstrap["unit"], bootstrap["confidence"]) != (
        10000,
        20261009,
        "episode",
        0.95,
    ):
        raise ValueError("Frozen paired episode-bootstrap contract changed")
    names = [v["name"] for v in plan["candidates"]]
    if not 2 <= len(names) <= 6 or len(set(names)) != len(names) or "native_reference" in names:
        raise ValueError("Freeze2..6 unique student candidates before final evaluation")
    if any(
        not name
        or any(
            c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_"
            for c in name
        )
        for name in names
    ):
        raise ValueError("Candidate names must be explicit simple artifact identifiers")
    for pair in plan["comparisons"]:
        if (
            pair["candidate"] not in names
            or pair["control"] not in [*names, "native_reference"]
            or pair["candidate"] == pair["control"]
        ):
            raise ValueError(
                "Comparison must reference explicit distinct frozen candidates/reference"
            )
    limits = plan["quality_gates"]
    if (
        limits["max_flow_ratio"] != 0.98
        or limits["max_combined_ratio"] != 0.98
        or not 1 <= limits["min_episodes_better"] <= len(final)
        or plan["native_retention"]["max_metric_ratio"] != 1.02
        or tuple(plan["native_retention"]["metrics"]) != NATIVE_METRICS
    ):
        raise ValueError("Final quality/retention thresholds or native metric definition changed")
    return len(final) * 32


def final_pairs(plan):
    return [
        {"episode": ep, "anchor": a, "nominal_seed": seed}
        for ep in plan["final"]
        for a in plan["eval_anchors"][str(ep)]
        for seed in plan["noise_seeds"]
    ]


class FinalCache:
    """No train/dev aliases: only the final cache generated by this joint run."""

    def __init__(self, root, plan, plan_sha, report_sha):
        self.root = Path(root)
        self.plan = plan
        self.report_sha = report_sha
        self.loaded = {}
        self.visited = set()
        report_path = self.root / "CACHE_RESULT.json"
        if sha(report_path) != report_sha:
            raise ValueError("Explicit completed final cache-report SHA required")
        self.report = read(report_path)
        expected = sum(len(plan["eval_anchors"][str(ep)]) for ep in plan["final"])
        if (
            self.report["status"] != "passed"
            or self.report["cohort"] != "final"
            or self.report["episodes"] != plan["final"]
            or self.report["plan_sha256"] != plan_sha
            or self.report["observations"] != expected
        ):
            raise ValueError("Final cache cohort/status/observation identity mismatch")
        self.paths = {}
        for row in self.report["files"]:
            path = self.root / row["file"]
            if (
                path.parent != self.root
                or path.stat().st_size != row["bytes"]
                or sha(path) != row["sha256"]
            ):
                raise ValueError("Final episode cache identity changed")
            self.paths[row["episode"]] = path
        if set(self.paths) != set(plan["final"]) or len(self.paths) != len(self.report["files"]):
            raise ValueError("Final cache episode inventory differs")

    def frame(self, episode, anchor):
        if episode not in self.paths or anchor not in self.plan["eval_anchors"][str(episode)]:
            raise ValueError("Frame is outside the frozen final-cohort anchor set")
        if episode not in self.loaded:
            value = torch.load(
                self.paths[episode], map_location="cpu", weights_only=True, mmap=True
            )
            if list(value) != self.plan["eval_anchors"][str(episode)]:
                raise ValueError("Final cache anchor order changed")
            self.loaded[episode] = value
        value = self.loaded[episode][anchor]
        if (episode, anchor) not in self.visited:
            if (
                value["episode"] != episode
                or value["anchor"] != anchor
                or frame_hash(value) != value["content_sha256"]
            ):
                raise ValueError("Final frame content identity changed")
            self.visited.add((episode, anchor))
        return value

    def assert_readonly(self):
        for ep, a in self.visited:
            value = self.loaded[ep][a]
            if frame_hash(value) != value["content_sha256"]:
                raise ValueError("Final cached frame was modified")
        if sha(self.root / "CACHE_RESULT.json") != self.report_sha:
            raise ValueError("Final cache report changed")


def evaluate_final_candidate(ctx, pairs, output):
    """Preserve evaluator mathematics and add final input/full-checkpoint identities."""
    output = Path(output)
    result_path = output / "RESULT.json"
    evaluator = periphery if ctx.candidate["kind"] == "core_periphery" else matched
    original = evaluator.write_new
    seen = 0

    def final_write(path, value):
        nonlocal seen
        if Path(path) == output / "details.json":
            for row in value:
                row["input_frame_content_sha256"] = ctx.cache.frame(row["episode"], row["anchor"])[
                    "content_sha256"
                ]
        if Path(path) == result_path:
            seen += 1
            if seen != 1 or value.get("scope") != OLD_SCOPE or result_path.exists():
                raise ValueError("Final metadata adapter only accepts one fresh original result")
            value["scope"] = FINAL_SCOPE
            value["cohort"] = "final"
            hashes = semantic_identity(ctx.student.state_dict(), ctx.candidate["kind"])
            value.update(
                checkpoint_kind=ctx.candidate["kind"],
                checkpoint_content_sha256=hashes["content_sha256"],
                student_content_sha256=hashes["content_sha256"],
                core_content_sha256=hashes["core_content_sha256"],
                periphery_content_sha256=hashes["periphery_content_sha256"],
            )
        original(path, value)

    with patch.object(evaluator, "write_new", final_write):
        result = evaluator.evaluate_pairs(ctx, pairs, output)
    if seen != 1:
        raise ValueError("Original metric helper did not produce its single terminal result")
    return result


def save_numpy_new(path, value):
    with Path(path).open("xb") as stream:
        np.save(stream, value, allow_pickle=False)


def verify_evaluation(record, expected_pairs):
    root = Path(record["path"]).parent
    if sha(record["path"]) != record["sha256"]:
        raise ValueError("Candidate result identity changed")
    result = read(record["path"])
    if (
        result["status"] != "passed"
        or result["rows"] != len(expected_pairs)
        or result["cohort"] != "final"
    ):
        raise ValueError("Incomplete or mislabeled final candidate evaluation")
    for name, digest in result["array_sha256"].items():
        if sha(root / f"{name}.npy") != digest:
            raise ValueError("Final candidate array identity changed")
    if (
        sha(root / "details.json") != result["details_sha256"]
        or sha(root / "NORMALIZATION.json") != result["normalization_sha256"]
    ):
        raise ValueError("Final candidate details/normalization changed")
    rows = read(root / "details.json")
    if len(rows) != len(expected_pairs):
        raise ValueError("Final candidate row count changed")
    for pair, row in zip(expected_pairs, rows):
        if (row["episode"], row["anchor"], row["seed"]) != (
            pair["episode"],
            pair["anchor"],
            pair["nominal_seed"],
        ):
            raise ValueError("Final candidate input order changed")
    return result, rows


def assert_teacher_equal(first_record, current_record, expected_pairs):
    first, left = verify_evaluation(first_record, expected_pairs)
    current, right = verify_evaluation(current_record, expected_pairs)
    for name in (
        "teacher_actions",
        "teacher_physical",
        "teacher_velocity",
        "physical_targets",
        "action_masks",
    ):
        if first["array_sha256"][name] != current["array_sha256"][name]:
            raise ValueError(f"Frozen teacher/target reference differs: {name}")
    for key in (
        "teacher_metrics",
        "teacher_per_episode",
        "normalization_sha256",
        "cache_report_sha256",
    ):
        if first[key] != current[key]:
            raise ValueError(f"Frozen teacher evaluation metadata differs: {key}")
    for a, b in zip(left, right):
        if (
            a["input_frame_content_sha256"] != b["input_frame_content_sha256"]
            or a["teacher_metrics"] != b["teacher_metrics"]
            or a["teacher_noise_receipt"] != b["teacher_noise_receipt"]
            or any(
                a["noise_receipt"][key] != b["noise_receipt"][key]
                for key in ("continuous_time", "discrete_time", "noisy_action", "forward_seed")
            )
        ):
            raise ValueError("Final candidate teacher/input/metric pairing differs")
    return True


def materialize_native_reference(first_record, output, base_hash, expected_pairs):
    result, rows = verify_evaluation(first_record, expected_pairs)
    source = Path(first_record["path"]).parent
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    mapping = {
        "student_actions": "teacher_actions",
        "teacher_actions": "teacher_actions",
        "student_physical": "teacher_physical",
        "teacher_physical": "teacher_physical",
        "student_velocity": "teacher_velocity",
        "teacher_velocity": "teacher_velocity",
        "physical_targets": "physical_targets",
        "action_masks": "action_masks",
    }
    for destination, origin in mapping.items():
        save_numpy_new(
            output / f"{destination}.npy", np.load(source / f"{origin}.npy", mmap_mode="r")
        )
    write_new(output / "NORMALIZATION.json", read(source / "NORMALIZATION.json"))
    native = []
    for row in rows:
        native.append(
            {k: row[k] for k in ("episode", "anchor", "seed", "paired_rng_seed")}
            | row["teacher_metrics"]
            | {
                "teacher_velocity_kd": 0.0,
                "teacher_action_physical_mae": 0.0,
                "teacher_metrics": row["teacher_metrics"],
                "noise_receipt": row["teacher_noise_receipt"],
                "teacher_noise_receipt": row["teacher_noise_receipt"],
                "identity_error_scope": "zero by self-identity, not a native retention metric",
            }
        )
    per_episode, metrics = aggregate_metrics(native, matched.METRICS)
    write_new(output / "details.json", native)
    value = {
        "status": "passed",
        "cohort": "final",
        "scope": "Native B0 outputs actually computed alongside the first student; materialized once from its independent teacher columns",
        "rows": len(native),
        "metrics": metrics,
        "per_episode": per_episode,
        "teacher_metrics": result["teacher_metrics"],
        "teacher_per_episode": result["teacher_per_episode"],
        "array_sha256": {k: sha(output / f"{k}.npy") for k in mapping},
        "details_sha256": sha(output / "details.json"),
        "normalization_sha256": sha(output / "NORMALIZATION.json"),
        "checkpoint_content_sha256": base_hash,
        "cache_report_sha256": result["cache_report_sha256"],
        "source_evaluation": {"path": first_record["path"], "sha256": first_record["sha256"]},
        "native_retention_metrics": list(NATIVE_METRICS),
    }
    write_new(output / "RESULT.json", value)
    return {
        "path": str((output / "RESULT.json").resolve()),
        "sha256": sha(output / "RESULT.json"),
        "result": value,
    }


def final_comparisons(results, plan):
    comparisons = []
    native = results["native_reference"]["metrics"]
    retention = {}
    for candidate in plan["candidates"]:
        name = candidate["name"]
        retention[name] = {
            key: results[name]["metrics"][key]
            <= native[key] * plan["native_retention"]["max_metric_ratio"]
            for key in plan["native_retention"]["metrics"]
        }
    for pair in plan["comparisons"]:
        candidate, control = results[pair["candidate"]], results[pair["control"]]
        report = paired_bootstrap(candidate, control, plan["final"], plan["paired_bootstrap"])
        report["scope"] = (
            "Paired pre-frozen final16 episode bootstrap; four sampling seeds are not independent training repetitions"
        )
        gates = {}
        for key, bound in (
            ("flow_loss", plan["quality_gates"]["max_flow_ratio"]),
            ("combined_mae_mixed_units", plan["quality_gates"]["max_combined_ratio"]),
        ):
            stats = report["metrics"][key]
            ratio = stats["ratio_of_episode_equal_means"]
            gates[key] = (
                ratio is not None
                and ratio <= bound
                and stats["episodes_better"] >= plan["quality_gates"]["min_episodes_better"]
            )
        comparisons.append(
            {
                **pair,
                "paired": report,
                "quality_gates": gates,
                "gt_quality_passed": all(gates.values()),
                "teacher_imitation_mean_difference": report["metrics"][
                    "teacher_action_physical_mae"
                ]["mean_difference"],
            }
        )
    return {
        "comparisons": comparisons,
        "native_retention": retention,
        "scope": "All frozen comparisons are reported; no result-based checkpoint selection or automatic downstream action",
    }
